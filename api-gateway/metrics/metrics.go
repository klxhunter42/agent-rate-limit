// GetInputPrice returns the input price per million tokens for a model. Falls back to $3/M.
func (m *Metrics) GetInputPrice(model string) float64 {
	if p, ok := m.pricing[model]; ok {
		return p.inputPerMillion
	}
	return 3.0
}

// Handler returns an HTTP handler that serves Prometheus metrics.
func (m *Metrics) Handler() http.Handler {
	return promhttp.HandlerFor(m.registry, promhttp.HandlerOpts{
		ErrorLog: log.New(io.Discard, "", 0),
	})
}

// statusWriter wraps http.ResponseWriter to capture the actual status code.
type statusWriter struct {
	http.ResponseWriter
	status int
}

func newStatusWriter(w http.ResponseWriter) *statusWriter {
	return &statusWriter{ResponseWriter: w, status: http.StatusOK}
}

func (sw *statusWriter) Hijack() (net.Conn, *bufio.ReadWriter, error) {
	if h, ok := sw.ResponseWriter.(http.Hijacker); ok {
		return h.Hijack()
	}
	return nil, nil, fmt.Errorf("response writer does not implement http.Hijacker")
}

func (sw *statusWriter) WriteHeader(code int) {
	sw.status = code
	sw.ResponseWriter.WriteHeader(code)
}

// Middleware instruments every request with latency and active-connection tracking.
func (m *Metrics) Middleware(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		m.ActiveConnections.Inc()
		defer m.ActiveConnections.Dec()

		sw := newStatusWriter(w)
		start := time.Now()

		next.ServeHTTP(sw, r)

		routePattern := chi.RouteContext(r.Context()).RoutePattern()
		if routePattern == "" || routePattern == "/*" {
			// Avoid unbounded cardinality from raw URL paths.
			routePattern = "_unknown"
		}

		status := strconv.Itoa(sw.status)
		duration := time.Since(start).Seconds()
		m.RequestLatency.WithLabelValues(r.Method, routePattern, status).Observe(duration)
	})
}

// IncError increments the error counter for the given error type.
func (m *Metrics) IncError(errType string) {
	m.ErrorRate.WithLabelValues(errType).Inc()
}

// IncRateLimit increments the rate-limit counter for the given key.
// Agent-specific keys are hashed to prevent unbounded cardinality.
func (m *Metrics) IncRateLimit(key string) {
	if strings.HasPrefix(key, "agent:") {
		h := sha1.Sum([]byte(key))
		key = "agent:" + hex.EncodeToString(h[:])[:8]
	}
	m.RateLimitHits.WithLabelValues(key).Inc()
}

// RecordTokens records input and output token usage for a model and accumulates cost.
func (m *Metrics) RecordTokens(ctx context.Context, model string, input, output int) {
	m.TokenInput.WithLabelValues(model).Add(float64(input))
	m.TokenOutput.WithLabelValues(model).Add(float64(output))
	var inputCost, outputCost float64
	var cost float64
	if p, ok := m.pricing[model]; ok {
		inputCost = float64(input) / 1_000_000 * p.inputPerMillion
		outputCost = float64(output) / 1_000_000 * p.outputPerMillion
		cost = inputCost + outputCost
		if inputCost > 0 {
			m.CostTotal.WithLabelValues(model, "input").Add(inputCost)
		}
		if outputCost > 0 {
			m.CostTotal.WithLabelValues(model, "output").Add(outputCost)
		}
	}
	if m.usageRecorder != nil && (input > 0 || output > 0) {
		m.usageRecorder(ctx, model, input, output, cost)
	}
}

// RecordCacheUsage records prompt cache token breakdown and estimated savings.
func (m *Metrics) RecordCacheUsage(model string, creation, read int) {
	if creation > 0 {
		m.CacheCreationTokens.WithLabelValues(model).Add(float64(creation))
	}
	if read > 0 {
		m.CacheReadTokens.WithLabelValues(model).Add(float64(read))
		if p, ok := m.pricing[model]; ok {
			savings := float64(read) / 1_000_000 * p.inputPerMillion * 0.9
			m.CacheSavingsTotal.WithLabelValues(model).Add(savings)
		}
	}
}

