// StartMockDataLoop continuously increments mock metrics so that rate()-based
// Grafana timeseries panels show live data. Stops when ctx is cancelled.
func (m *Metrics) StartMockDataLoop(ctx context.Context) {
	go func() {
		ticker := time.NewTicker(5 * time.Second)
		defer ticker.Stop()

		techniques := []struct {
			name     string
			charsInc float64
			runsInc  int
			duration float64
		}{
			{"chunker", 120, 1, 0.012},
			{"delta", 80, 1, 0.008},
			{"sketch_dedup", 40, 1, 0.005},
			{"semantic_dedup", 30, 1, 0.025},
			{"disclosure", 0, 2, 0.003},
			{"packer", 15, 1, 0.015},
			{"bandit", 0, 3, 0.042},
			{"prefetcher", 0, 2, 0.006},
			{"summarizer", 90, 1, 0.085},
			{"warmstart", 0, 2, 0.018},
			{"caveman", 50, 1, 0.035},
		}

		wasteDetectors := []struct {
			name     string
			findings int
			tokens   float64
		}{
			{"repetition", 2, 80},
			{"padding", 1, 50},
			{"off_topic", 1, 30},
			{"redundancy", 1, 40},
		}

		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				for _, t := range techniques {
					if t.charsInc > 0 {
						m.OptimizerCharsSaved.WithLabelValues(t.name, "input").Add(t.charsInc)
					}
					for i := 0; i < t.runsInc; i++ {
						m.OptimizerRuns.WithLabelValues(t.name).Inc()
					}
					m.OptimizerDuration.WithLabelValues(t.name).Observe(t.duration)
				}

				m.OptimizerTokensSaved.WithLabelValues("input").Add(40)
				m.CostSavings.WithLabelValues("claude-sonnet-4-6").Add(0.003)

				severities := []string{"low", "medium", "high"}
				for _, d := range wasteDetectors {
					for _, sev := range severities {
						for j := 0; j < d.findings; j++ {
							m.WasteFindings.WithLabelValues(d.name, sev).Inc()
						}
					}
					m.WasteTokensWasted.WithLabelValues(d.name).Add(d.tokens)
				}
			}

			// Billing/profile continuous data
			billingTickPaths := []struct {
				path    string
				model   string
				profile string
				latency float64
			}{
				{"go_direct", "claude-sonnet-4-6", "default", 1.1},
				{"zai_proxy", "glm-5.1", "default", 3.2},
				{"openai_proxy", "gpt-4o", "default", 1.7},
			}
			for _, bp := range billingTickPaths {
				m.BillingPathRequests.WithLabelValues(bp.path, bp.model, bp.profile).Inc()
				m.BillingPathLatency.WithLabelValues(bp.path, bp.model).Observe(bp.latency)
			}
			m.ProfileRequests.WithLabelValues("default", "claude-sonnet-4-6").Add(2)
			m.ProfileTokenIn.WithLabelValues("default", "claude-sonnet-4-6").Add(120)
			m.ProfileTokenOut.WithLabelValues("default", "claude-sonnet-4-6").Add(30)
			m.ProfileCost.WithLabelValues("default", "claude-sonnet-4-6", "input").Add(0.00036)
			m.ProfileCost.WithLabelValues("default", "claude-sonnet-4-6", "output").Add(0.00045)
		}
	}()
}

// mockLoopState tracks the running mock data loop.
type mockLoopState struct {
	mu      sync.Mutex
	cancel  context.CancelFunc
	running bool
}

var mockLoop mockLoopState

// StartMockLoop starts the continuous mock data loop. Returns false if already running.
func (m *Metrics) StartMockLoop() bool {
	mockLoop.mu.Lock()
	defer mockLoop.mu.Unlock()
	if mockLoop.running {
		return false
	}
	ctx, cancel := context.WithCancel(context.Background())
	mockLoop.cancel = cancel
	mockLoop.running = true
	m.StartMockDataLoop(ctx)
	return true
}

// StopMockLoop stops the continuous mock data loop. Returns false if not running.
func (m *Metrics) StopMockLoop() bool {
	mockLoop.mu.Lock()
	defer mockLoop.mu.Unlock()
	if !mockLoop.running {
		return false
	}
	mockLoop.cancel()
	mockLoop.running = false
	return true
}

// MockLoopRunning returns whether the mock data loop is active.
func (m *Metrics) MockLoopRunning() bool {
	mockLoop.mu.Lock()
	defer mockLoop.mu.Unlock()
	return mockLoop.running
}
